/// Native process runtime record.
struct ManagedProcess {
    /// Immutable native process metadata.
    meta: ProcessMeta,
    /// Child process handle; stopping and monitoring must verify its PID.
    child: Mutex<Child>,
    /// Whether the process is still running.
    running: AtomicBool,
    /// Exit code; i32::MIN until the process exits.
    exit_code: AtomicI32,
    /// Whether termination was triggered by a timeout.
    timed_out: AtomicBool,
    /// Bounded stdout buffer.
    stdout: Mutex<Vec<u8>>,
    /// Bounded stderr buffer.
    stderr: Mutex<Vec<u8>>,
    /// Number of stdout bytes truncated.
    stdout_dropped: AtomicUsize,
    /// Number of stderr bytes truncated.
    stderr_dropped: AtomicUsize,
}

/// Immutable native process metadata.
struct ProcessMeta {
    /// Native record ID.
    id: String,
    /// Owning task ID.
    task_id: String,
    /// Identity value derived from the PID and startup information.
    identity: String,
    /// Operating-system PID.
    pid: u32,
    /// Program text.
    program: String,
    /// Argument array.
    args: Vec<String>,
    /// Canonical current directory.
    cwd: String,
    /// Startup timestamp in milliseconds.
    started_at: u128,
    /// Per-stream output retention limit.
    output_limit: usize,
}

