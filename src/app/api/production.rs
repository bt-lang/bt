//! Production desktop API.
//!
//! This module consolidates streaming HTTP, application credentials, workspace files,
//! subprocesses, and application-owned data in the native Rust layer. All long-lived
//! collections have fixed limits. Stream cancellation closes the event gate before notifying
//! the request task, preventing dispatch after cancellation. Path and cleanup operations use
//! canonical paths and cannot escape their boundaries through textual prefixes.

use futures_util::StreamExt;
use serde::{Deserialize, Serialize};
use serde_json::Value as JsonValue;
use sha2::{Digest, Sha256};
use std::collections::HashMap;
use std::fs::{self, File, OpenOptions};
use std::io::{Read, Write};
use std::path::{Component, Path, PathBuf};
use std::process::{Child, Command, Stdio};
use std::sync::atomic::{AtomicBool, AtomicI32, AtomicUsize, Ordering};
use std::sync::{Arc, Mutex};
use std::thread;
use std::time::{Duration, Instant, SystemTime, UNIX_EPOCH};
use tauri::WebviewWindow;
use tokio::sync::watch;
use uuid::Uuid;

/// Streaming HTTP DOM event name.
pub const HTTP_STREAM_EVENT: &str = "bt://http/stream";
/// Native process DOM event name.
pub const PROCESS_EVENT: &str = "bt://process/event";
/// BT backend call completion event name.
pub const BACKEND_EVENT: &str = "bt://backend/event";

/// Maximum number of concurrent streaming requests.
const MAX_STREAMS: usize = 8;
/// Maximum bytes allowed for one streaming response.
const MAX_STREAM_BYTES: usize = 4_000_000;
/// Maximum chunk events dispatched for one response.
const MAX_STREAM_CHUNKS: usize = 16_384;
/// Maximum number of registered workspaces.
const MAX_WORKSPACES: usize = 8;
/// Maximum bytes per workspace read.
const MAX_WORKSPACE_READ_BYTES: usize = 4 * 1024 * 1024;
/// Maximum entries per workspace listing.
const MAX_WORKSPACE_ENTRIES: usize = 4_096;
/// Maximum number of registered native processes.
const MAX_PROCESSES: usize = 32;
/// Default retention limit for each process output stream.
const DEFAULT_PROCESS_OUTPUT_LIMIT: usize = 64 * 1024;
/// Maximum retention limit for each process output stream.
const MAX_PROCESS_OUTPUT_LIMIT: usize = 1024 * 1024;
/// Cleanup confirmation ticket lifetime.
const CLEANUP_TICKET_TTL: Duration = Duration::from_secs(120);

/// Shared state for the production desktop API.
pub struct ProductionState {
    /// Internal state that can safely move into async tasks and output threads.
    inner: Arc<Mutex<ProductionStateInner>>,
}

/// Bounded internal state for the production desktop API.
struct ProductionStateInner {
    /// Streaming requests currently allowed to dispatch events to the page.
    streams: HashMap<String, StreamControl>,
    /// Canonical workspaces registered by the current window.
    workspaces: HashMap<String, WorkspaceRoot>,
    /// Processes started by the current window that can still be queried or stopped precisely.
    processes: HashMap<String, Arc<ManagedProcess>>,
    /// Short-lived ticket from the most recent data cleanup preview.
    cleanup_ticket: Option<CleanupTicket>,
}

/// Cancellation channel and event sequence for one streaming request.
struct StreamControl {
    /// Cancellation notification; removing the map entry also ends the receiver immediately.
    cancel: watch::Sender<bool>,
    /// Next event sequence number.
    sequence: u64,
}

/// Canonical workspace root.
#[derive(Clone)]
struct WorkspaceRoot {
    /// Absolute root resolved by the operating system.
    root: PathBuf,
}

/// Secondary confirmation ticket for data cleanup.
struct CleanupTicket {
    /// The ticket is valid only for the application data root that created it.
    app_name: String,
    /// Unpredictable one-time confirmation value.
    token: String,
    /// Time when the ticket was created.
    created_at: Instant,
}

/// Plaintext JSON application credential file; the caller explicitly selects this format for
/// easier migration and manual maintenance.
#[derive(Deserialize, Serialize)]
struct CredentialFile {
    /// File format version.
    schema: u32,
    /// Stable credential ID supplied by the caller.
    credential_id: String,
    /// Credential plaintext stored verbatim.
    api_key: String,
}

/// Streaming request options.
#[derive(Clone, Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct HttpStreamOptions {
    /// Request ID generated by the page so listeners can be installed before startup.
    pub request_id: String,
    /// HTTP request URL; only http/https is allowed.
    pub url: String,
    /// HTTP method; streaming calls with a request body typically use POST.
    #[serde(default = "default_post_method")]
    pub method: String,
    /// Non-sensitive request headers; Authorization and Cookie must be managed by the native layer.
    #[serde(default)]
    pub headers: HashMap<String, String>,
    /// UTF-8 request body.
    #[serde(default)]
    pub body: String,
    /// Application credential ID; an empty value omits Authorization.
    #[serde(default)]
    pub credential_id: String,
    /// Total request timeout in milliseconds.
    #[serde(default = "default_http_timeout_ms")]
    pub timeout_ms: u64,
    /// Response body byte limit; the request ends immediately if exceeded.
    #[serde(default = "default_stream_bytes")]
    pub max_response_bytes: usize,
}

/// Streaming request startup result.
#[derive(Clone, Debug, Serialize)]
pub struct HttpStreamStart {
    /// Stable request ID.
    pub request_id: String,
    /// Concurrent request limit for the current process.
    pub active_limit: usize,
    /// Effective response byte limit for the current request.
    pub max_response_bytes: usize,
}

/// Streaming event dispatched to the page.
#[derive(Clone, Debug, Serialize)]
struct HttpStreamPayload {
    /// Request ID.
    request_id: String,
    /// Strictly increasing event sequence number.
    sequence: u64,
    /// start, headers, chunk, done, error, or cancelled.
    kind: String,
    /// HTTP status code; 0 until response headers arrive.
    status: u16,
    /// Current chunk text or the final complete response text.
    data: String,
    /// Redacted user-visible error.
    message: String,
    /// Response bytes received so far.
    received_bytes: usize,
}

